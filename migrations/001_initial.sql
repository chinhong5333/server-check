CREATE TABLE IF NOT EXISTS agents (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  public_id CHAR(36) NOT NULL,
  project_id BIGINT UNSIGNED NOT NULL,
  server_name VARCHAR(120) NOT NULL,
  health_api_url VARCHAR(2048) NOT NULL,
  health_request_timeout_seconds INT UNSIGNED NOT NULL,
  apache_service_name VARCHAR(120) NOT NULL,
  credential_hash CHAR(64) NOT NULL,
  credential_hint VARCHAR(12) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'new',
  probable_cause VARCHAR(255) NULL,
  agent_version VARCHAR(40) NULL,
  last_heartbeat_at BIGINT UNSIGNED NULL,
  last_metrics_at BIGINT UNSIGNED NULL,
  last_validation_error VARCHAR(500) NULL,
  last_ram_available_percent DECIMAL(6,2) NULL,
  last_disk_available_percent DECIMAL(6,2) NULL,
  last_load_5_per_core DECIMAL(12,4) NULL,
  last_health_outcome VARCHAR(20) NULL,
  last_health_http_status_code SMALLINT UNSIGNED NULL,
  last_health_latency_ms INT UNSIGNED NULL,
  created_at BIGINT UNSIGNED NOT NULL,
  updated_at BIGINT UNSIGNED NOT NULL,
  is_delete TINYINT(1) NOT NULL DEFAULT 0,
  PRIMARY KEY (id),
  UNIQUE KEY uq_agents_public_id (public_id),
  UNIQUE KEY uq_agents_project_name (project_id, server_name),
  KEY idx_agents_project_status (project_id, is_delete, status),
  KEY idx_agents_due (is_delete, last_heartbeat_at),
  CONSTRAINT fk_agents_project FOREIGN KEY (project_id) REFERENCES projects (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;


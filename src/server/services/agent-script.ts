export interface AgentScriptInput {
  agentId: string;
  projectName: string;
  agentName: string;
  credential: string;
  centralApiUrl: string;
  healthApiUrl: string | null;
  healthRequestTimeoutSeconds: number;
}

export const AGENT_VERSION = "1.5.0";
export const APACHE_AUTO_DETECT_LABEL = "auto-detect";

export function shellSingleQuote(value: string): string {
  return `'${value.replaceAll("'", `'\"'\"'`)}'`;
}

export function shellCommentValue(value: string): string {
  return value
    .replace(/[\u0000-\u001f\u007f\u2028\u2029]+/g, " ")
    .replace(/\s+/g, " ")
    .replaceAll("\\", "/")
    .trim();
}

/** Default install location suggested to the operator; the setup UI lets them change it. */
export function defaultAgentScriptPath(scriptFilename: string): string {
  return `/root/${scriptFilename}`;
}

/** The agent reports every minute; the agent's heartbeat interval only sets the missing-heartbeat timeout. */
export function agentCronEntry(scriptPath: string): string {
  return `* * * * * /bin/sh ${shellSingleQuote(scriptPath)}`;
}

export function normalizeHealthApiUrl(value: string): string {
  const url = new URL(value);
  if (url.protocol !== "http:" && url.protocol !== "https:") {
    throw new Error("health_api_url must use http or https.");
  }
  if (url.username || url.password) {
    throw new Error("health_api_url must not contain embedded credentials.");
  }
  url.hash = "";
  return url.toString();
}

/** Every value below is a shell variable that already holds valid JSON (a number, null, or a quoted string). */
const PAYLOAD_TEMPLATE =
  `{"sequence_id":$SEQUENCE_ID,"observed_at":$OBSERVED_AT,"agent_version":"$AGENT_VERSION",` +
  `"health_probe":{"checked_at":$CHECKED_AT,"outcome":"$HEALTH_OUTCOME","http_status_code":$HTTP_STATUS_JSON,"latency_ms":$LATENCY_MS,"error_code":$ERROR_CODE_JSON,"error_message":$ERROR_MESSAGE_JSON},` +
  `"database_health":$DB_HEALTH_JSON,` +
  `"metrics":{"cpu_count":$CPU_COUNT,"load_1":$LOAD_1,"load_5":$LOAD_5,"load_15":$LOAD_15,"memory_total_bytes":$MEMORY_TOTAL_BYTES,"memory_available_bytes":$MEMORY_AVAILABLE_BYTES,"swap_total_bytes":$SWAP_TOTAL_BYTES,"swap_free_bytes":$SWAP_FREE_BYTES,"uptime_seconds":$UPTIME_SECONDS},` +
  `"filesystems":$FILESYSTEMS_JSON,"top_processes":$TOP_PROCESSES_JSON,` +
  `"service_checks":{"apache":{"service_name":"$APACHE_SERVICE_NAME","status":"$APACHE_STATUS"},"nginx":{"service_name":"nginx","status":"$NGINX_STATUS"}}}`;

/**
 * Builds the agent script. Since 1.5.0 it runs every check it can (Apache, Nginx, and Middleware API when a URL is set)
 * and the central server applies each agent's on/off settings, so turning a check on or off never needs a new script.
 * The script is POSIX sh and keeps process count low: every minute it forks about two dozen times, not seventy.
 */
export function generateAgentScript(input: AgentScriptInput): string {
  const lines = [
    "#!/bin/sh",
    "# Server Check agent — generated by the central backoffice.",
    `# Project: ${shellCommentValue(input.projectName)}`,
    `# Agent: ${shellCommentValue(input.agentName)}`,
    "# This file contains a credential. Keep it owner-readable only (chmod 700).",
    "set -u",
    "umask 077",
    "# Cron runs with a minimal PATH; service binaries such as nginx and apache2 usually live in sbin.",
    "PATH=\"/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin${PATH:+:$PATH}\"",
    "export PATH",
    "",
    "DRY_RUN='0'",
    "case \"${1:-}\" in",
    "  '') ;;",
    "  --dry-run) DRY_RUN='1' ;;",
    "  *) printf '%s\\n' \"Usage: $0 [--dry-run]\" >&2; exit 2 ;;",
    "esac",
    "",
    `AGENT_VERSION=${shellSingleQuote(AGENT_VERSION)}`,
    `AGENT_ID=${shellSingleQuote(input.agentId)}`,
    `AGENT_CREDENTIAL=${shellSingleQuote(input.credential)}`,
    `CENTRAL_API_URL=${shellSingleQuote(input.centralApiUrl)}`,
    `HEALTH_API_URL=${shellSingleQuote(input.healthApiUrl ?? "")}`,
    `HEALTH_TIMEOUT=${shellSingleQuote(String(input.healthRequestTimeoutSeconds))}`,
    `APACHE_SERVICE_NAME=${shellSingleQuote(APACHE_AUTO_DETECT_LABEL)}`,
    "# The lock directory is also this run's private scratch space, so one rm removes everything and no file name is guessable.",
    "LOCK_DIR=\"${TMPDIR:-/tmp}/server-check-${AGENT_ID}.lock\"",
    "ERROR_FILE=\"$LOCK_DIR/curl.error\"",
    "HEALTH_BODY_FILE=\"$LOCK_DIR/health.json\"",
    "DF_FILE=\"$LOCK_DIR/df\"",
    "INODE_FILE=\"$LOCK_DIR/inode\"",
    "",
    "if ! mkdir \"$LOCK_DIR\" 2>/dev/null; then",
    "  # A run killed mid-way (OOM, kill -9) leaves its lock behind; reclaim it after 5 minutes instead of staying silent until reboot.",
    "  if [ -n \"$(find \"$LOCK_DIR\" -maxdepth 0 -mmin +5 2>/dev/null)\" ]; then rm -rf \"$LOCK_DIR\"; fi",
    "  if ! mkdir \"$LOCK_DIR\" 2>/dev/null; then",
    "    printf '%s\\n' \"Server Check agent is already running; skipping overlap.\" >&2",
    "    exit 0",
    "  fi",
    "fi",
    "",
    "cleanup() {",
    "  rm -rf \"$LOCK_DIR\" 2>/dev/null || true",
    "}",
    "trap cleanup EXIT INT TERM",
    "",
    "json_escape() {",
    "  printf '%s' \"$1\" | awk 'BEGIN { ORS=\"\" } { if (NR > 1) printf \"\\\\n\"; gsub(/\\\\/, \"\\\\\\\\\"); gsub(/\"/, \"\\\\\\\"\"); gsub(/\\r/, \"\\\\r\"); gsub(/\\t/, \"\\\\t\"); printf \"%s\", $0 }'",
    "}",
    "",
    "extract_database_health() {",
    "  if command -v node >/dev/null 2>&1; then",
    "    node - \"$HEALTH_BODY_FILE\" <<'JS'",
    "const fs = require('fs');",
    "const count = (value) => { const number = Number(value); return Number.isInteger(number) && number >= 0 && number <= 10000000 ? number : null; };",
    "const size = (value) => { const number = Number(value); return Number.isFinite(number) && number >= 0 && number <= 1000000000000000 ? number : null; };",
    "const safeRaw = (value, depth = 0) => { if (value === null || typeof value === 'boolean') return true; if (typeof value === 'number') return Number.isFinite(value); if (typeof value === 'string') return value.length <= 4000; if (depth >= 10) return false; if (Array.isArray(value)) return value.length <= 100 && value.every((item) => safeRaw(item, depth + 1)); if (typeof value !== 'object') return false; const entries = Object.entries(value); return entries.length <= 100 && entries.every(([key, item]) => key.length <= 120 && safeRaw(item, depth + 1)); };",
    "try {",
    "  const root = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));",
    "  const value = root && root.db;",
    "  if (!value || typeof value !== 'object' || Array.isArray(value)) process.exit(0);",
    "  const status = typeof value.status === 'string' && value.status.trim() ? value.status.trim().toLowerCase().slice(0, 40) : 'unknown';",
    "  const message = typeof value.message === 'string' ? value.message.slice(0, 500) : '';",
    "  const result = { status, message, connection_count: count(value.connection_count), connection_max: count(value.connection_max), threads_running: count(value.threads_running), peak_connections: count(value.peak_connections), long_queries: count(value.long_queries), db_size_mb: size(value.db_size_mb) };",
    "  if (safeRaw(value) && JSON.stringify(value).length <= 32768) result.raw = value;",
    "  process.stdout.write(JSON.stringify(result));",
    "} catch {}",
    "JS",
    "    return",
    "  fi",
    "  if command -v python3 >/dev/null 2>&1; then",
    "    python3 - \"$HEALTH_BODY_FILE\" <<'PY'",
    "import json, math, sys",
    "def number(value, integer=False, limit=1000000000000000):",
    "    try: result = float(value)",
    "    except (TypeError, ValueError): return None",
    "    if not math.isfinite(result) or result < 0 or result > limit or (integer and not result.is_integer()): return None",
    "    return int(result) if integer else result",
    "def safe_raw(value, depth=0):",
    "    if value is None or isinstance(value, bool): return True",
    "    if isinstance(value, (int, float)): return math.isfinite(value)",
    "    if isinstance(value, str): return len(value) <= 4000",
    "    if depth >= 10: return False",
    "    if isinstance(value, list): return len(value) <= 100 and all(safe_raw(item, depth + 1) for item in value)",
    "    if isinstance(value, dict): return len(value) <= 100 and all(isinstance(key, str) and len(key) <= 120 and safe_raw(item, depth + 1) for key, item in value.items())",
    "    return False",
    "try:",
    "    with open(sys.argv[1], encoding='utf-8') as source: root = json.load(source)",
    "    value = root.get('db') if isinstance(root, dict) else None",
    "    if isinstance(value, dict):",
    "        status_value = value.get('status')",
    "        status = status_value.strip().lower()[:40] if isinstance(status_value, str) and status_value.strip() else 'unknown'",
    "        message_value = value.get('message')",
    "        message = message_value[:500] if isinstance(message_value, str) else ''",
    "        result = {'status': status, 'message': message, 'connection_count': number(value.get('connection_count'), True, 10000000), 'connection_max': number(value.get('connection_max'), True, 10000000), 'threads_running': number(value.get('threads_running'), True, 10000000), 'peak_connections': number(value.get('peak_connections'), True, 10000000), 'long_queries': number(value.get('long_queries'), True, 10000000), 'db_size_mb': number(value.get('db_size_mb'))}",
    "        raw_json = json.dumps(value, separators=(',', ':'))",
    "        if safe_raw(value) and len(raw_json) <= 32768: result['raw'] = value",
    "        print(json.dumps(result, separators=(',', ':')), end='')",
    "except (OSError, ValueError, TypeError):",
    "    pass",
    "PY",
    "  fi",
    "}",
    "",
    "CHECKED_AT=\"$(date +%s000)\"",
    "HEALTH_OUTCOME='disabled'",
    "HEALTH_ERROR_CODE=''",
    "ERROR_MESSAGE=''",
    "HTTP_STATUS_JSON='null'",
    "LATENCY_MS='null'",
    "DB_HEALTH_JSON='null'",
    "if [ -n \"$HEALTH_API_URL\" ]; then",
    "HEALTH_META=\"$(curl --silent --show-error --output \"$HEALTH_BODY_FILE\" --write-out '%{http_code}|%{time_total}' --max-time \"$HEALTH_TIMEOUT\" \"$HEALTH_API_URL\" 2>\"$ERROR_FILE\")\"",
    "CURL_EXIT=$?",
    "HTTP_STATUS=\"${HEALTH_META%%|*}\"",
    "LATENCY_MS=\"$(awk -v seconds=\"${HEALTH_META#*|}\" 'BEGIN { if (seconds ~ /^[0-9.]+$/) printf \"%d\", seconds * 1000 }')\"",
    "LATENCY_MS=\"${LATENCY_MS:-null}\"",
    "HEALTH_OUTCOME='unhealthy'",
    "HEALTH_ERROR_CODE='unknown_error'",
    "",
    "if [ \"$CURL_EXIT\" -eq 0 ] && [ \"$HTTP_STATUS\" = '200' ]; then",
    "  HEALTH_OUTCOME='healthy'",
    "  HEALTH_ERROR_CODE=''",
    "  HTTP_STATUS_JSON='200'",
    "  DB_HEALTH_JSON=\"$(extract_database_health 2>/dev/null || true)\"",
    "  if [ -z \"$DB_HEALTH_JSON\" ]; then DB_HEALTH_JSON='null'; fi",
    "elif [ \"$CURL_EXIT\" -eq 0 ]; then",
    "  HEALTH_ERROR_CODE='http_status_error'",
    "  case \"$HTTP_STATUS\" in ''|*[!0-9]*) ;; *) HTTP_STATUS_JSON=\"$HTTP_STATUS\" ;; esac",
    "else",
    "  case \"$CURL_EXIT\" in",
    "    6) HEALTH_ERROR_CODE='dns_error' ;;",
    "    7) HEALTH_ERROR_CODE='connection_error' ;;",
    "    28) HEALTH_ERROR_CODE='timeout' ;;",
    "    35|51|58|60) HEALTH_ERROR_CODE='tls_error' ;;",
    "    *) HEALTH_ERROR_CODE='unknown_error' ;;",
    "  esac",
    "fi",
    "if [ \"$HEALTH_OUTCOME\" != 'healthy' ]; then",
    "  ERROR_MESSAGE=\"$(head -c 400 \"$ERROR_FILE\" 2>/dev/null | tr '\\r\\n' ' ')\"",
    "fi",
    "",
    "fi",
    "",
    "# One awk pass over /proc for memory, load and uptime; a missing or malformed value is sent as null.",
    "set -- $(awk '",
    "  BEGIN { for (i = 1; i <= 8; i++) value[i] = \"null\" }",
    "  FILENAME == \"/proc/meminfo\" && $2 ~ /^[0-9]+$/ {",
    "    if ($1 == \"MemTotal:\") value[1] = sprintf(\"%.0f\", $2 * 1024)",
    "    else if ($1 == \"MemAvailable:\") value[2] = sprintf(\"%.0f\", $2 * 1024)",
    "    else if ($1 == \"SwapTotal:\") value[3] = sprintf(\"%.0f\", $2 * 1024)",
    "    else if ($1 == \"SwapFree:\") value[4] = sprintf(\"%.0f\", $2 * 1024)",
    "  }",
    "  FILENAME == \"/proc/loadavg\" { for (i = 1; i <= 3; i++) if ($i ~ /^[0-9.]+$/) value[4 + i] = $i }",
    "  FILENAME == \"/proc/uptime\" && $1 ~ /^[0-9.]+$/ { value[8] = sprintf(\"%d\", $1) }",
    "  END { for (i = 1; i <= 8; i++) printf \"%s \", value[i] }",
    "' /proc/meminfo /proc/loadavg /proc/uptime 2>/dev/null)",
    "MEMORY_TOTAL_BYTES=\"${1:-null}\"; MEMORY_AVAILABLE_BYTES=\"${2:-null}\"; SWAP_TOTAL_BYTES=\"${3:-null}\"; SWAP_FREE_BYTES=\"${4:-null}\"",
    "LOAD_1=\"${5:-null}\"; LOAD_5=\"${6:-null}\"; LOAD_15=\"${7:-null}\"; UPTIME_SECONDS=\"${8:-null}\"",
    "CPU_COUNT=\"$(getconf _NPROCESSORS_ONLN 2>/dev/null)\"",
    "case \"$CPU_COUNT\" in ''|*[!0-9]*) CPU_COUNT='null' ;; esac",
    "",
    "df -PkP -x tmpfs -x devtmpfs >\"$DF_FILE\" 2>/dev/null || df -PkP >\"$DF_FILE\" 2>/dev/null || : >\"$DF_FILE\"",
    "df -PiP -x tmpfs -x devtmpfs >\"$INODE_FILE\" 2>/dev/null || df -PiP >\"$INODE_FILE\" 2>/dev/null || : >\"$INODE_FILE\"",
    "# Mount points may contain spaces, so the mount point is everything after the fifth column.",
    "FILESYSTEMS_JSON=\"$(awk '",
    "  function escape_json(value) { gsub(/\\\\/, \"\\\\\\\\\", value); gsub(/\"/, \"\\\\\\\"\", value); return value }",
    "  function mount_point(    value, i) { value = $6; for (i = 7; i <= NF; i++) value = value \" \" $i; return value }",
    "  BEGIN { printf \"[\" }",
    "  FNR == 1 { next }",
    "  FILENAME == ARGV[1] { mount = mount_point(); gsub(/%/, \"\", $5); inode[mount] = $5; next }",
    "  count < 32 && $2 ~ /^[0-9]+$/ && $4 ~ /^[0-9]+$/ {",
    "    if (count++) printf \",\"",
    "    mount = mount_point()",
    "    inode_value = ((mount in inode) && inode[mount] ~ /^[0-9.]+$/) ? inode[mount] : \"null\"",
    "    printf \"{\\\"filesystem\\\":\\\"%s\\\",\\\"mount_point\\\":\\\"%s\\\",\\\"total_bytes\\\":%.0f,\\\"available_bytes\\\":%.0f,\\\"inode_used_percent\\\":%s}\", escape_json($1), escape_json(mount), $2 * 1024, $4 * 1024, inode_value",
    "  }",
    "  END { printf \"]\" }",
    "' \"$INODE_FILE\" \"$DF_FILE\")\"",
    "",
    "# One systemctl call per service. Older systemd (CentOS 7) lacks --value, so the key=value lines are matched instead.",
    "# Sets SERVICE_STATE to absent when the unit is not loaded, otherwise active, inactive or unknown.",
    "service_state() {",
    "  SERVICE_SHOW=\"$(systemctl show \"$1.service\" --property=LoadState,ActiveState 2>/dev/null)\"",
    "  case \"$SERVICE_SHOW\" in",
    "    *'LoadState=loaded'*) ;;",
    "    *) SERVICE_STATE='absent'; return ;;",
    "  esac",
    "  case \"$SERVICE_SHOW\" in",
    "    *'ActiveState=active'*|*'ActiveState=reloading'*) SERVICE_STATE='active' ;;",
    "    *'ActiveState=inactive'*|*'ActiveState=failed'*|*'ActiveState=deactivating'*) SERVICE_STATE='inactive' ;;",
    "    *) SERVICE_STATE='unknown' ;;",
    "  esac",
    "}",
    "# Apache and Nginx are always checked; a missing service or failed command never stops the heartbeat.",
    "APACHE_STATUS='unknown'",
    "if [ -x '/opt/lampp/lampp' ]; then",
    "  APACHE_SERVICE_NAME='lampp-apache'",
    "  LAMPP_STATUS=\"$(LC_ALL=C /opt/lampp/lampp status 2>/dev/null)\"",
    "  case \"$LAMPP_STATUS\" in",
    "    *'Apache is not running.'*) APACHE_STATUS='inactive' ;;",
    "    *'Apache is running.'*) APACHE_STATUS='active' ;;",
    "  esac",
    "elif command -v systemctl >/dev/null 2>&1; then",
    "  for APACHE_CANDIDATE in apache2 httpd; do",
    "    service_state \"$APACHE_CANDIDATE\"",
    "    if [ \"$SERVICE_STATE\" != 'absent' ]; then",
    "      APACHE_SERVICE_NAME=\"$APACHE_CANDIDATE\"",
    "      APACHE_STATUS=\"$SERVICE_STATE\"",
    "      break",
    "    fi",
    "  done",
    "fi",
    `if [ "$APACHE_STATUS" = 'unknown' ] && [ "$APACHE_SERVICE_NAME" = ${shellSingleQuote(APACHE_AUTO_DETECT_LABEL)} ] && ! command -v apache2 >/dev/null 2>&1 && ! command -v httpd >/dev/null 2>&1; then`,
    "  APACHE_STATUS='not_installed'",
    "fi",
    "NGINX_STATUS='unknown'",
    "NGINX_UNIT_STATE='absent'",
    "if command -v systemctl >/dev/null 2>&1; then",
    "  service_state nginx",
    "  NGINX_UNIT_STATE=\"$SERVICE_STATE\"",
    "  if [ \"$NGINX_UNIT_STATE\" != 'absent' ]; then NGINX_STATUS=\"$NGINX_UNIT_STATE\"; fi",
    "fi",
    "if [ \"$NGINX_STATUS\" = 'unknown' ] && command -v pgrep >/dev/null 2>&1; then",
    "  if pgrep -x nginx >/dev/null 2>&1; then",
    "    NGINX_STATUS='active'",
    "  elif command -v nginx >/dev/null 2>&1; then",
    "    NGINX_STATUS='inactive'",
    "  fi",
    "fi",
    "if [ \"$NGINX_STATUS\" = 'unknown' ] && [ \"$NGINX_UNIT_STATE\" = 'absent' ] && ! command -v nginx >/dev/null 2>&1; then",
    "  NGINX_STATUS='not_installed'",
    "fi",
    "",
    "# The command column comes last because process names may contain spaces.",
    "TOP_PROCESSES_JSON=\"$(ps -eo %cpu=,%mem=,comm= --sort=-%cpu 2>/dev/null | awk 'NR <= 5 { command = $0; sub(/^[ \\t]*[^ \\t]+[ \\t]+[^ \\t]+[ \\t]+/, \"\", command); sub(/[ \\t]+$/, \"\", command); gsub(/\\\\/, \"\\\\\\\\\", command); gsub(/\"/, \"\\\\\\\"\", command); if (count++) printf \",\"; printf \"{\\\"command\\\":\\\"%s\\\",\\\"cpu_percent\\\":%s,\\\"memory_percent\\\":%s}\", command, $1 + 0, $2 + 0 }')\"",
    "TOP_PROCESSES_JSON=\"[$TOP_PROCESSES_JSON]\"",
    "OBSERVED_AT=\"$(date +%s000)\"",
    "SEQUENCE_ID=\"$OBSERVED_AT\"",
    "# Error codes are fixed identifiers; only the curl message needs JSON escaping.",
    "ERROR_CODE_JSON='null'",
    "ERROR_MESSAGE_JSON='null'",
    "if [ -n \"$HEALTH_ERROR_CODE\" ]; then ERROR_CODE_JSON=\"\\\"$HEALTH_ERROR_CODE\\\"\"; fi",
    "if [ -n \"$ERROR_MESSAGE\" ]; then ERROR_MESSAGE_JSON=\"\\\"$(json_escape \"$ERROR_MESSAGE\")\\\"\"; fi",
    "",
    `PAYLOAD="${PAYLOAD_TEMPLATE.replaceAll('"', '\\"')}"`,
    "",
    "if [ \"$DRY_RUN\" = '1' ]; then",
    "  printf '%s\\n' \"$PAYLOAD\"",
    "  exit 0",
    "fi",
    "",
    "if ! printf '%s' \"$PAYLOAD\" | curl --silent --show-error --fail --max-time 20 --retry 2 --retry-delay 1 --request POST --header 'Content-Type: application/json' --header \"Authorization: Bearer $AGENT_CREDENTIAL\" --data-binary @- \"$CENTRAL_API_URL\" >/dev/null; then",
    "  printf '%s\\n' \"Server Check could not report to the central API.\" >&2",
    "  exit 1",
    "fi",
    "",
    "printf '%s\\n' \"Server Check heartbeat delivered.\"",
    ""
  ];

  return `${lines.join("\n")}\n`;
}
